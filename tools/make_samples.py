def write_docx(name: str, lines: list[tuple[str, str]], out_dir: Path) -> Path:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Microsoft YaHei"
    style.font.size = Pt(10.5)
    for kind, text in lines:
        if kind == "h":
            para = doc.add_paragraph()
            run = para.add_run(text)
            run.bold = True
            run.font.size = Pt(14 if len(text) <= 4 else 12)
        else:
            doc.add_paragraph(text)
    path = out_dir / name
    doc.save(path)
    return path


def write_pdf(name: str, lines: list[tuple[str, str]], out_dir: Path) -> Path | None:
    try:
        import pymupdf
    except ImportError:
        return None

    doc = pymupdf.open()
    page = doc.new_page()
    # 使用内置 CJK 字体，保证中文可显示
    fontname = "china-s"
    text = ""
    for kind, line in lines:
        text += ("**" if kind == "h" else "") + line + "\n"
    rect = pymupdf.Rect(50, 50, 545, 800)
    page.insert_textbox(rect, text.replace("**", ""), fontsize=10.5, fontname=fontname, lineheight=1.5)
    path = out_dir / name
    doc.save(path)
    doc.close()
    return path


def main() -> None:
    out_dir = ROOT / "samples"
    out_dir.mkdir(exist_ok=True)
    for name, lines in SAMPLES.items():
        write_docx(name, lines, out_dir)
        print("created", name)

    # 额外生成一份 PDF，验证 PDF 解析链路
    pdf_name = "林静-数据分析师（PDF）.pdf"
    pdf_path = write_pdf(pdf_name, SAMPLES["孙悦-数据分析师.docx"], out_dir)
    if pdf_path:
        print("created", pdf_name)
    else:
        print("skip pdf (pymupdf missing)")


if __name__ == "__main__":
    main()
